// Writes the self-hosted font entries into dist (vite.config.ts runs it after each build):
//   fonts-self-hosted.css   Bricolage Grotesque (wght and the opsz 12..96 axis) and Geist Mono as woff2 files shipped in
//                           dist/fonts, plus the metric-matched fallback faces. No request leaves the consumer's origin.
//   fonts-fallback.css      only the two fallback faces, for an app that serves the real fonts its own way.
// The woff2 files come from the Fontsource variable packages (devDependencies), one per unicode-range subset, so a
// browser fetches only the subsets a page uses. Both typefaces are under the SIL Open Font License 1.1, whose text
// ships beside them. The fallback faces are read from src/styles/fonts.css, so there is one copy of their metrics.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import postcss, { type AtRule } from "postcss";

const require = createRequire(import.meta.url);

interface Face {
  /** The Fontsource package's folder (a literal require.resolve, so knip sees the dependency). */
  dir: string;
  /** Its stylesheet with the axes eos uses. */
  css: string;
  /** The family name eos's tokens ask for. */
  family: string;
  /** The licence file name in dist/fonts. */
  licence: string;
}

const FACES: Face[] = [
  {
    dir: dirname(require.resolve("@fontsource-variable/bricolage-grotesque/package.json")),
    css: "opsz.css",
    family: "Bricolage Grotesque",
    licence: "BricolageGrotesque-OFL.txt",
  },
  {
    dir: dirname(require.resolve("@fontsource-variable/geist-mono/package.json")),
    css: "wght.css",
    family: "Geist Mono",
    licence: "GeistMono-OFL.txt",
  },
];

const HEADER = `/*
 * Self-hosted fonts, opt-in: import \`@eos-ui/vue/fonts-self-hosted.css\` to use the library's typefaces with no request to
 * a third party. Bricolage Grotesque (weights 200 to 800, optical size 12 to 96) and Geist Mono (100 to 900) are served
 * from the woff2 files beside this stylesheet, one per script subset. Your bundler copies them with the CSS.
 * Both are under the SIL Open Font License 1.1 (fonts/*-OFL.txt). The two "Fallback" faces are shown while the real
 * fonts load, scaled to their metrics. Generated by scripts/fonts.ts from the Fontsource packages.
 */
`;

/** The fallback @font-face rules of src/styles/fonts.css. */
function fallbackFaces(pkgRoot: string): string {
  const root = postcss.parse(readFileSync(join(pkgRoot, "src", "styles", "fonts.css"), "utf8"));
  const faces: string[] = [];
  root.walkAtRules("font-face", (rule) => {
    if (/Fallback"/.test(rule.toString())) faces.push(rule.toString());
  });
  if (faces.length !== 2) throw new Error(`src/styles/fonts.css: expected 2 fallback faces, found ${faces.length}`);
  return faces.join("\n\n") + "\n";
}

export function writeFonts(pkgRoot: string) {
  const dist = join(pkgRoot, "dist");
  const out = join(dist, "fonts");
  mkdirSync(out, { recursive: true });
  const rules: string[] = [];
  for (const face of FACES) {
    const { dir } = face;
    const css = postcss.parse(readFileSync(join(dir, face.css), "utf8"));
    css.walkAtRules("font-face", (rule: AtRule) => {
      // Upright only: the components use no italic.
      if (rule.nodes?.some((d) => d.type === "decl" && d.prop === "font-style" && d.value !== "normal")) return;
      rule.walkDecls((d) => {
        if (d.prop === "font-family") d.value = `"${face.family}"`;
        if (d.prop === "src")
          d.value = d.value.replace(/url\(\.\/files\/([^)]+)\)/g, (_, file: string) => {
            copyFileSync(join(dir, "files", file), join(out, file));
            return `url("./fonts/${file}")`;
          });
      });
      rules.push(rule.toString());
    });
    copyFileSync(join(dir, "LICENSE"), join(out, face.licence));
  }
  const fallback = fallbackFaces(pkgRoot);
  writeFileSync(join(dist, "fonts-self-hosted.css"), `${HEADER}\n${rules.join("\n\n")}\n\n${fallback}`);
  writeFileSync(
    join(dist, "fonts-fallback.css"),
    `/*\n * The metric-matched fallback faces only ("Bricolage Grotesque Fallback", "Geist Mono Fallback"), for an app that\n * serves the real fonts itself. See fonts.css for how they are measured.\n */\n${fallback}`,
  );
}
