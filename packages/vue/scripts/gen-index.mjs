// Writes src/index.ts, the public entry, from what is on disk, so adding a component or composable
// never means editing a shared file (and two people never conflict on it).
//   src/components/<Name>/index.ts   -> exported
//   src/composables/<name>.ts        -> exported (not *.test.ts)
import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src");
const components = existsSync(join(root, "components"))
  ? readdirSync(join(root, "components"), { withFileTypes: true })
      .filter((d) => d.isDirectory() && existsSync(join(root, "components", d.name, "index.ts")))
      .map((d) => d.name)
      .sort()
  : [];
const composables = existsSync(join(root, "composables"))
  ? readdirSync(join(root, "composables"))
      .filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts"))
      .map((f) => f.slice(0, -3))
      .sort()
  : [];

const lines = [
  "// Generated by scripts/gen-index.mjs. Do not edit.",
  'export { createEos } from "./plugin.js";',
  'export type { Eos, EosOptions } from "./plugin.js";',
  'export { useConfig, useMessages, useIconMarkup, usePortalTarget, CONFIG_KEY } from "./config.js";',
  'export type { EosConfig, Translate } from "./config.js";',
  'export { defaultMessages } from "./messages.js";',
  'export type { MessageKey } from "./messages.js";',
  'export { phosphor } from "./icons/phosphor.js";',
  'export type { IconName, IconMarkup } from "./icons/phosphor.js";',
  'export { defineTheme } from "@eos-ui/tokens";',
  'export type { Theme, ThemeInput } from "@eos-ui/tokens";',
  ...composables.map((c) => `export * from "./composables/${c}.js";`),
  ...components.map((c) => `export * from "./components/${c}/index.js";`),
  "",
];
writeFileSync(join(root, "index.ts"), lines.join("\n"));
console.log(`index.ts: ${components.length} components, ${composables.length} composables`);
