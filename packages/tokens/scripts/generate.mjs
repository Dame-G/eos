import { readFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import ts from "typescript";
import { writeGenerated, reportStale } from "../../../scripts/generated.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = JSON.parse(readFileSync(join(root, "src/tokens.json"), "utf8"));

const FAMILIES = [
  "color",
  "spacing",
  "layout",
  "radius",
  "shadow",
  "fontSize",
  "tracking",
  "leading",
  "size",
  "stroke",
  "depth",
  "duration",
  "easing",
  "zIndex",
  "weight",
];
const WEIGHT = { 400: "regular", 500: "medium", 600: "strong" };

// A type style becomes a `font` shorthand token: weight, size, line-height and family in one value.
const typeTokens = src.type.groups.flatMap((g) =>
  g.styles.map((s) => ({
    name: `type-${s.name}`,
    value: `var(--e-weight-${WEIGHT[s.fontWeight]}) var(--e-${s.size}) / var(--e-leading-${s.leading}) var(--e-font-${s.family ?? g.family})`,
    usage: s.usage,
    from: "fonts,textScale",
  })),
);
const tokensOf = (family) => (family === "type" ? typeTokens : src[family].tokens);

const flat = {};
for (const family of [...FAMILIES, "type"]) for (const t of tokensOf(family)) flat[t.name] = t.value;
flat["font-sans"] = src.type.families.sans;
flat["font-mono"] = src.type.families.mono;
flat["font-script"] = src.type.families.script;

for (const [k, v] of Object.entries(flat)) {
  const m = /^\{([a-z0-9-]+)\}$/.exec(v);
  if (m) flat[k] = `var(--e-${m[1]})`;
}

const groups = Object.fromEntries([...FAMILIES, "type"].map((f) => [f, tokensOf(f).map((t) => t.name)]));
groups.font = ["font-sans", "font-mono", "font-script"];

const usage = {};
const derivedFrom = { "font-sans": "fonts", "font-mono": "fonts", "font-script": "fonts" };
const constants = [];
const inputTokens = ["font-sans", "font-mono", "font-script"];
for (const family of [...FAMILIES, "type"])
  for (const t of tokensOf(family)) {
    usage[t.name] = t.usage;
    if (t.from) derivedFrom[t.name] = t.from;
    if (t.constant) constants.push(t.name);
    if (t.input) inputTokens.push(t.name);
  }

const colors = new Set(src.color.tokens.map((t) => t.name));
const out = `// Generated by scripts/generate.mjs from src/tokens.json. Do not edit.
export const defaults = ${JSON.stringify(flat, null, 2)} as const;
export const groups = ${JSON.stringify(groups, null, 2)} as const;
export const usage: Record<string, string> = ${JSON.stringify(usage, null, 2)};
export const derivedFrom: Record<string, string> = ${JSON.stringify(derivedFrom, null, 2)};
export const constants: string[] = ${JSON.stringify(constants)};
export const inputTokens: string[] = ${JSON.stringify(inputTokens)};
export type TokenName = keyof typeof defaults;
export const colorNames: ReadonlySet<string> = new Set(${JSON.stringify([...colors])});
`;
mkdirSync(join(root, "src/generated"), { recursive: true });
// `--check` writes nothing and exits 1 when the committed file is stale.
await writeGenerated(join(root, "src/generated/defaults.ts"), out);
await writeGenerated(join(root, "src/generated/theme-inputs.ts"), themeInputsModule());

/** The inputs of `defineTheme()`, read from the `ThemeInput` interface in theme.ts: name, doc comment and type as written. */
function themeInputsModule() {
  const file = join(root, "src/theme.ts");
  const source = ts.createSourceFile(file, readFileSync(file, "utf8"), ts.ScriptTarget.Latest, true);
  const decl = source.statements.find((s) => ts.isInterfaceDeclaration(s) && s.name.text === "ThemeInput");
  if (!decl) throw new Error("theme.ts has no ThemeInput interface");
  const literals = new Map(
    source.statements
      .filter(
        (s) =>
          ts.isTypeAliasDeclaration(s) &&
          ts.isUnionTypeNode(s.type) &&
          s.type.types.every((t) => ts.isLiteralTypeNode(t) && ts.isStringLiteral(t.literal)),
      )
      .map((s) => [s.name.text, s.type.getText(source)]),
  );
  const inputs = decl.members.filter(ts.isPropertySignature).map((m) => {
    const doc = ts
      .getJSDocCommentsAndTags(m)
      .map((d) => ts.getTextOfJSDocComment(d.comment) ?? "")
      .join(" ")
      .trim();
    if (!doc) throw new Error(`ThemeInput.${m.name.getText(source)} has no doc comment`);
    // A preset alias (`ContrastPreset`) is spelled out as its literals, so a reader sees the values.
    const alias = ts.isTypeReferenceNode(m.type) && literals.get(m.type.typeName.getText(source));
    const type = alias || m.type.getText(source).replace(/\s+/g, " ").replace(/; }/g, " }");
    return { name: m.name.getText(source), doc, type };
  });
  return `// Generated by scripts/generate.mjs from the ThemeInput interface in src/theme.ts. Do not edit.
import type { ThemeInput } from "../theme.js";

/** One input of \`defineTheme()\`: its name, its doc comment and its type as written in \`ThemeInput\`. */
export interface ThemeInputDoc {
  name: keyof ThemeInput;
  doc: string;
  type: string;
}

/** Every input of \`defineTheme()\`, in the order \`ThemeInput\` declares them, for documentation and tooling. */
export const themeInputs: readonly ThemeInputDoc[] = ${JSON.stringify(inputs, null, 2)};
`;
}
reportStale("pnpm tokens");
console.log(`tokens: ${Object.keys(flat).length} values`);
